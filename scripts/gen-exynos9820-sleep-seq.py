"""Extract the SYS_SLEEP PMUCAL sequences from Samsung's SM-G973F kernel source into a C header.

Usage: gen-exynos9820-sleep-seq.py <flexpmu_cal_system_exynos9820.h> > exynos9820-sleep-seq.h
The arrays are copied verbatim (PMUCAL_SEQ_DESC rows), renamed with an s10_ prefix.
"""
import re, sys

src = open(sys.argv[1]).read()
names = ['enter_sleep', 'save_sleep', 'exit_sleep', 'earlywkup_sleep']
print('/* SPDX-License-Identifier: GPL-2.0 */')
print('/* Generated by scripts/gen-exynos9820-sleep-seq.py from Samsung SM-G973F kernel')
print(' * drivers/soc/samsung/cal-if/exynos9820/flexpmu_cal_system_exynos9820.h (GPL-2.0). Do not edit. */')
for n in names:
    m = re.search(r'struct pmucal_seq %s\[\] = \{(.*?)\n\};' % n, src, re.S)
    if not m:
        sys.exit('missing ' + n)
    print('\nstatic struct pmucal_seq s10_%s[] = {%s\n};' % (n, m.group(1)))
