"""Turn Samsung's D-PHY T_HS_SETTLE table into drivers/s10-camera-v4l2/exynos9820-csis-settle.h.

Source: fimc-is-hw-settle-8nm-lpp.h (LineageOS/android_kernel_samsung_exynos9820, commit
4bcfb0263b21b553760a3bdce542452db3184820), the table Samsung's fimc_is_hw_find_settle()
searches with the data rate (Mbit/s per lane) rounded up to 10. The table is a dense
descending series 6500..80 in steps of 10, stored here as one byte per step.
"""
from pathlib import Path
import hashlib
import re
import sys

def main():
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference-file', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    src, out = args.reference_file, args.output
    data = src.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    EXPECT = 'b7318344da9dbd24305c34ad37cd8f600c0a5158ebbaac76a2c317c7a44e8e41'
    if digest != EXPECT:
        sys.exit(f'unexpected SHA-256 {digest}')
    text = data.decode()
    text = text[text.index('fimc_is_csi_settle_table'):]
    pairs = [(int(a), int(b)) for a, b in re.findall(r'(\d+)\s*,\s*(\d+)\s*,', text)]
    speeds = [s for s, _ in pairs]
    assert speeds == list(range(6500, 70, -10)), 'table is not dense'
    vals = [v for _, v in pairs]
    assert all(0 < v < 256 for v in vals)
    rows = ['\t' + ', '.join(str(v) for v in vals[i:i + 16]) + ',' for i in range(0, len(vals), 16)]
    out.write_text(f'''/* SPDX-License-Identifier: GPL-2.0-only
 * T_HS_SETTLE values Copyright (c) Samsung Electronics Co., Ltd.
 * Generated by scripts/prepare-csis-settle.py from fimc-is-hw-settle-8nm-lpp.h
 * (LineageOS/android_kernel_samsung_exynos9820 commit
 * 4bcfb0263b21b553760a3bdce542452db3184820, SHA-256 {digest}).
 * Index i is the lane rate 6500 - 10 * i Mbit/s; do not edit.
 */
#define CSIS_SETTLE_MAX_RATE	{speeds[0]}
#define CSIS_SETTLE_MIN_RATE	{speeds[-1]}
static const u8 csis_settle_table[] = {{
''' + '\n'.join(rows) + '\n};\n')
    print(out, len(vals))


if __name__ == "__main__":
    main()
